class AlembicTestHarness:
    """A wrapper around Alembic commands for testing."""

    def __init__(self, alembic_cfg: Config) -> None:
        self.alembic_cfg = alembic_cfg

    def ensure_version_table(self) -> None:
        """Create the alembic_version table and stamp it with the latest revision.

        This prevents "revision not found" errors during autogenerate on a clean database.
        """
        command.stamp(self.alembic_cfg, "head")

    def generate_autogen_revision(
        self, metadata: MetaData, message: str, include_object: Callable[..., bool] | None = None
    ) -> None:
        """Autogenerate a revision against ``metadata``, optionally filtered by ``include_object``."""
        self.ensure_version_table()
        self.alembic_cfg.attributes["target_metadata"] = metadata
        if include_object is not None:
            self.alembic_cfg.attributes["include_object"] = include_object
        self.revision(message=message, autogenerate=True)

    def revision(self, message: str, autogenerate: bool = False) -> None:
        command.revision(self.alembic_cfg, message=message, autogenerate=autogenerate)

    def upgrade(self, revision: str) -> None:
        command.upgrade(self.alembic_cfg, revision)

    def downgrade(self, revision: str) -> None:
        command.downgrade(self.alembic_cfg, revision)


class AlembicTestEnv(NamedTuple):
    """The Alembic environment a system test runs in."""

    versions_path: Path
    alembic_cfg: Config
    harness: AlembicTestHarness


class _AlembicLifecycleBase(fixtures.TestBase):
    """Provides the ``database``, ``sr_engine`` and ``alembic_env`` fixtures the system tests use.

    Gated on sqlalchemy_2: the dialect's Alembic integration needs SQLAlchemy 2.0.
    """

    __backend__ = True
    __only_on__ = "starrocks"
    __requires__ = ("sqlalchemy_2",)

    @testing.fixture
    def database(self) -> Iterator[str]:
        """A database of its own for the test, dropped afterwards."""
        name = f"{config.db.url.database}_lc_{uuid.uuid4().hex[:12]}"
        with config.db.begin() as conn:
            conn.exec_driver_sql(f"CREATE DATABASE `{name}`")
        yield name
        with config.db.begin() as conn:
            conn.exec_driver_sql(f"DROP DATABASE IF EXISTS `{name}` FORCE")

    @testing.fixture
    def sr_engine(self, database: str) -> Engine:
        """An engine on the test's own database."""
        return engines.testing_engine(url=config.db.url.set(database=database))

    @testing.fixture
    def alembic_env(self, sr_engine: Engine) -> Iterator[AlembicTestEnv]:
        """An Alembic environment in the staging directory, pointing at the test's database."""
        env.clear_staging_env()
        env.staging_env()
        try:
            env.env_file_fixture(ENV_PY)
            env.script_file_fixture(SCRIPT_PY_MAKO)
            scripts = Path(env._get_staging_directory()) / "scripts"
            alembic_cfg = env._write_config_file(
                ALEMBIC_INI.format(
                    script_location=scripts.as_posix(),
                    url=sr_engine.url.render_as_string(hide_password=False).replace("%", "%%"),
                )
            )
            yield AlembicTestEnv(
                versions_path=scripts / "versions", alembic_cfg=alembic_cfg, harness=AlembicTestHarness(alembic_cfg)
            )
        finally:
            env.clear_staging_env()


class ScriptContentParser:
    """Reads autogenerated revision scripts and pulls out their upgrade and downgrade bodies."""

    UPGRADE_EXTRACTION_REGEX = re.compile(UPGRADE_STR + r"(.*?)" + DOWNGRADE_STR, re.DOTALL)
    DOWNGRADE_EXTRACTION_REGEX = re.compile(DOWNGRADE_STR + r"(.*)", re.DOTALL)

    @classmethod
    def check_script_content(cls, alembic_env: AlembicTestEnv, script_num: int, script_name: str) -> str:
        """Assert there are ``script_num`` revisions named ``script_name`` and return the first one's text."""
        scripts = list(alembic_env.versions_path.glob(f"*{script_name}.py"))
        assert len(scripts) == script_num
        script_content = scripts[0].read_text()
        logger.debug(f"script_content:\n>>>>\n{script_content}\n<<<<")
        return script_content

    @classmethod
    def _extract_upgrade_or_downgrade_content(cls, header: re.Pattern, script: str) -> str | None:
        match = header.search(script)
        if not match:
            return None
        content = match.group(1)
        content = f"    {content.rstrip()}" if content else None
        logger.debug(f"upgrade/downgrade content:\n>>>>\n{content}\n<<<<")
        return content

    @classmethod
    def extract_upgrade_content(cls, script: str) -> str | None:
        """Extract the body of the upgrade() function from an Alembic migration script."""
        return cls._extract_upgrade_or_downgrade_content(cls.UPGRADE_EXTRACTION_REGEX, script)

    @classmethod
    def extract_downgrade_content(cls, script: str) -> str | None:
        """Extract the body of the downgrade() function from an Alembic migration script."""
        return cls._extract_upgrade_or_downgrade_content(cls.DOWNGRADE_EXTRACTION_REGEX, script)

    @classmethod
    def extract_non_comment_lines(cls, content: str) -> list[str]:
        """Extract the non-comment lines from an Alembic migration script."""
        non_comment_lines = [
            line for line in content.split("\n") if line.strip() and not line.strip().startswith("#")
        ]
        non_comment_lines_str = "\n".join(non_comment_lines)
        logger.debug(f"non comment lines:\n>>>>\n{non_comment_lines_str}\n<<<<")
        return non_comment_lines


def wait_for_alter_table_attributes(
    inspector: Inspector,
    table_name: str,
    attribute_name: str,
    expected_value: str,
    max_round: int = 20,
    sleep_time: int = 3,
) -> dict[str, Any] | None:
    """Poll the table's options until ``attribute_name`` has ``expected_value``, then return the options."""
    options = None
    value = None
    for i in range(max_round):
        inspector.clear_cache()
        options = inspector.get_table_options(table_name)
        logger.debug(
            f"get table options (round={i + 1}) for table: {table_name}, attribute: {attribute_name}. %s", options
        )
        value = options[attribute_name].strip()
        if expected_value == value:
            break
        time.sleep(sleep_time)
    assert expected_value == value
    return options


def wait_for_alter_table_column_or_optimization(
    engine: Engine,
    table_name: str,
    alter_type: str,
    schema: str | None = None,
    max_round: int = 20,
    sleep_time: int = 3,
) -> bool:
    """Wait until no ``alter_type`` ("COLUMN" or "OPTIMIZE") job on the table is in a non-final state."""
    states = ["PENDING", "RUNNING", "WAITING_TXN", "FINISHED_REWRITING"]
    done = False
    for i in range(max_round):
        done = False
        for state in states:
            done = _wait_for_alter_table_state(engine, table_name, alter_type, schema, 1, 0, state=state)
            logger.debug(f"show alter table {state}(round={i + 1}) for table: {schema}.{table_name}. done: {done}")
            if not done:
                break
        if done:
            break
        time.sleep(sleep_time)
    return done


def _wait_for_alter_table_state(
    engine: Engine,
    table_name: str,
    alter_type: str,
    schema: str | None = None,
    max_round: int = 20,
    sleep_time: int = 3,
    state: str = "RUNNING",
) -> bool:
    """Wait for the table to have no ``alter_type`` job in ``state``; True when there is none left.

    The state may not change right after the ALTER TABLE statement returns successfully.
    """
    with engine.connect() as conn:
        for _ in range(max_round):
            show_alter_table_row = StarRocksDialect.get_show_alter_table(
                conn, table_name, alter_type, schema, state=state
            )
            if not show_alter_table_row:
                break
            logger.debug(f"show_alter_table_row for table: {table_name}, state: {state}. row: {show_alter_table_row}")
            time.sleep(sleep_time)
        if show_alter_table_row:
            logger.warning("ALTER TABLE is still %s for table: %s", state, table_name)
    return not show_alter_table_row
